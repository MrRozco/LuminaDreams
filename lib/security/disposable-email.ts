function getAdditionalDisposableDomainsFromEnv() {
  const raw = process.env.DISPOSABLE_EMAIL_BLOCKLIST ?? "";
  return raw
    .split(",")
    .map((item) => item.trim().toLowerCase())
    .filter(Boolean);
}

export function isDisposableEmail(email: string) {
  const at = email.lastIndexOf("@");
  if (at === -1) return false;

  const domain = email.slice(at + 1).toLowerCase();
  if (!domain) return false;

  if (DEFAULT_DISPOSABLE_DOMAINS.has(domain)) {
    return true;
  }

  const additional = getAdditionalDisposableDomainsFromEnv();
  return additional.includes(domain);
}
